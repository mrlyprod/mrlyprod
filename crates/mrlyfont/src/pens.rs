/// Returns every pen in font order: uppers, lowers, digits, extras, specials.
pub fn all() -> Vec<Pen> {
    [UPPERS, LOWERS, DIGITS, EXTRAS, SPECIALS]
        .into_iter()
        .flatten()
        .copied()
        .collect()
}
