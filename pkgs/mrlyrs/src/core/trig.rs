/// Returns the sine at a sample index, wrapping past a full turn.
#[inline]
pub fn sin_idx(i: usize) -> f32 {
    SINE[i % N]
}

/// Returns the cosine at a sample index by a quarter-turn shift of the sine table.
#[inline]
pub fn cos_idx(i: usize) -> f32 {
    SINE[(i + N / 4) % N]
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn quarter_turns_are_exact() {
        assert_eq!((cos_idx(0), sin_idx(0)), (1.0, 0.0));
        assert_eq!(sin_idx(N / 4), 1.0);
        assert!(cos_idx(N / 4).abs() < 1e-6);
        assert!(sin_idx(N / 2).abs() < 1e-6);
        assert_eq!(sin_idx(3 * N / 4), -1.0);
    }

    #[test]
    fn stride_divides_every_count() {
        for &count in &[1usize, 2, 4, 8, 16, 32, 64, 128] {
            assert_eq!(N % count, 0, "N must divide count {count}");
        }
    }
}
