const ROWS = 5;

/* BANNER */

export function banner(text: string, ink = "#") {
  const glyphs = [...text.toUpperCase()].map((ch) => FACE[ch] ?? FACE[" "]!);
  return Array.from({ length: ROWS }, (_, y) =>
    glyphs
      .map((rows) => rows[y]!)
      .join(".")
      .replaceAll("#", ink)
      .replaceAll(".", " ")
      .trimEnd(),
  ).join("\n");
}

/* GAUGE */

export function gauge(at: number, cells: number) {
  const full = Math.round(Math.min(1, Math.max(0, at)) * cells);
  return `[${"#".repeat(full)}${"-".repeat(cells - full)}]`;
}
